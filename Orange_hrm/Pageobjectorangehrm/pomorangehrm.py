from selenium import webdriver
from selenium.webdriver.common.by import By

class Loginpage:
    txt_username_Xpath='//*[@id="app"]/div[1]/div/div[1]/div/div[2]/div[2]/form/div[1]/div/div[2]/input'
    txt_passwd_Xpath='//*[@id="app"]/div[1]/div/div[1]/div/div[2]/div[2]/form/div[2]/div/div[2]/input'
    btn_login_Xpath='//*[@id="app"]/div[1]/div/div[1]/div/div[2]/div[2]/form/div[3]/button'

    def __init__(self,driver):
        self.driver=driver

    def setusername(self,username):
        usertxt=self.driver.find_element(By.XPATH,self.txt_username_Xpath)
        usertxt.send_keys(username)

    def setpasswd(self,passwd):
        passtxt=self.driver.find_element(By.XPATH,self.txt_passwd_Xpath)
        passtxt.send_keys(passwd)

    def setbtnlick(self,button):
        btnclick=self.driver.find_element(By.XPATH,self.btn_login_Xpath)
        btnclick.click()



























































































































































































































































































































































































































































































































































































































































